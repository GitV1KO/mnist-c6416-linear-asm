#!/usr/bin/env python3
"""Convert upstream integer text files into a C89-compatible embedded header."""
import argparse
import hashlib
from itertools import islice
from pathlib import Path


def integers(path, limit=None):
    with path.open(encoding="ascii") as stream:
        lines = stream if limit is None else islice(stream, limit)
        return [int(line.strip()) for line in lines]


def emit_array(name, kind, values, dimensions=None):
    dimensions = dimensions or f"[{len(values)}]"
    lines = [f"static const {kind} {name}{dimensions} = {{"]
    for offset in range(0, len(values), 28):
        lines.append("    " + ",".join(str(v) for v in values[offset:offset+28]) + ",")
    lines.append("};")
    return "\n".join(lines)


def emit_images(values, count):
    lines = [f"static const unsigned char cnn_images[{count}][784] = {{"]
    for sample in range(count):
        lines.append("    {")
        start = sample * 784
        for row in range(28):
            pixels = values[start+row*28:start+(row+1)*28]
            lines.append("        " + ",".join(str(v) for v in pixels) + ",")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=root / "data")
    parser.add_argument("--count", type=int, default=20)
    parser.add_argument("--offset", type=int, default=0)
    parser.add_argument("--output", type=Path, default=root / "conv/cnn_data.h")
    args = parser.parse_args()
    if args.count <= 0 or args.offset < 0:
        parser.error("count must be positive; offset must be nonnegative")
    arrays = []
    counts = {"w1": 125, "b1": 5, "w2": 1250, "b2": 10, "w3": 100, "b3": 10}
    for name, expected in counts.items():
        upstream_name = f"conv{name[1]}_{name[0]}.txt"
        values = integers(args.data_dir / upstream_name)
        if len(values) != expected:
            raise ValueError(f"{upstream_name}: expected {expected}, got {len(values)}")
        if any(value < -32768 or value > 32767 for value in values):
            raise ValueError(f"{upstream_name}: value cannot fit signed short")
        arrays.append(emit_array(f"cnn_{name}", "short", values))
    stop = args.offset + args.count
    images = integers(args.data_dir / "data.txt", stop * 784)
    labels = integers(args.data_dir / "label.txt", stop)
    if len(images) != stop * 784 or len(labels) != stop:
        raise ValueError("dataset is shorter than the requested sample range")
    images = images[args.offset*784:]
    labels = labels[args.offset:]
    if any(value not in (0, 1) for value in images):
        raise ValueError("images must contain binary 0/1 pixels")
    if any(value < 0 or value > 9 for value in labels):
        raise ValueError("labels must be 0..9")
    digest = hashlib.sha256(bytes(images) + bytes(labels)).hexdigest()
    arrays.append(emit_images(images, args.count))
    arrays.append(emit_array("cnn_labels", "unsigned char", labels))
    text = (
        "/* Generated by tools/embed_data.py; no runtime file I/O. */\n"
        f"/* Samples [{args.offset}, {stop}); image+label SHA256: {digest} */\n"
        "#ifndef CNN_DATA_H\n#define CNN_DATA_H\n"
        f"#define CNN_SAMPLE_COUNT {args.count}\n"
        f"#define CNN_SAMPLE_OFFSET {args.offset}\n\n"
        + "\n\n".join(arrays) + "\n\n#endif\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="ascii")
    print(f"Generated {args.output}: {args.count} embedded samples")


if __name__ == "__main__":
    main()
