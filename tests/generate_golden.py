#!/usr/bin/env python3
"""Generate score/prediction goldens with the untouched upstream C mathematics.

Only the upstream main symbol and Windows file paths are replaced in a
temporary source copy. CNN production code and the .sa kernel are not linked.
Requires standard-library Python 3 and host clang, not TensorFlow or TI tools.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
from verify_host import verify_exported_header


ORACLE_MAIN = r'''
#undef main
#include <cnn_data.h>
int main(void)
{
    int sample, j, n, c;
    long long sum, term;
    get_weights();
    for (sample = 0; sample < CNN_SAMPLE_COUNT; ++sample) {
        for (j = 0; j < 784; ++j) input[j / 28][j % 28] = cnn_images[sample][j];
        output = 0;
        model_run();
        /* The host long is wider than TI COFF long. Reject golden data that
           would exceed upstream's signed 40-bit products/partial sums. */
        for (n = 0; n < 10; ++n) {
            sum = 0;
            for (c = 0; c < 10; ++c) {
                term = (long long)layer3_pool[c] * conv3_w[c][n];
                sum += term;
                if (term < -549755813888LL || term > 549755813887LL ||
                    sum < -549755813888LL || sum > 549755813887LL) return 2;
            }
            sum += conv3_b[n];
            if (sum < -549755813888LL || sum > 549755813887LL) return 2;
            if (sum != layer3_conv[n]) return 3;
        }
        printf("GOLDEN %d", output);
        for (n = 0; n < 10; ++n) printf(" %lld", (long long)layer3_conv[n]);
        printf("\n");
    }
    return 0;
}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--data-header", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--clang", default="clang")
    args = parser.parse_args()
    project = args.project.resolve()
    header = (args.data_header or project / "conv" / "cnn_data.h").resolve()
    destination = (args.output or project / "conv" / "cnn_golden.h").resolve()
    compiler = shutil.which(args.clang)
    if not compiler:
        raise RuntimeError("clang is not installed or is not on PATH")
    verify_exported_header(header, project / "data")
    text = header.read_text()
    count = int(re.search(r"#\s*define\s+CNN_SAMPLE_COUNT\s+(\d+)", text).group(1))
    offset = int(re.search(r"#\s*define\s+CNN_SAMPLE_OFFSET\s+(\d+)", text).group(1))
    # Hash the complete file, including weights and formatting, not merely the
    # image/label digest in its comment. No fingerprint macro is added to data.
    digest = hashlib.sha256(header.read_bytes()).hexdigest()
    original = (project / "reference" / "main.c").read_text()
    original = original.replace(r"..\\data\\", str(project / "data") + "/")
    with tempfile.TemporaryDirectory(prefix="cnn-upstream-golden-") as name:
        temp = Path(name)
        (temp / "cnn_data.h").write_text(text)
        oracle = temp / "oracle.c"
        oracle.write_text("#define main upstream_unused_main\n" + original + ORACLE_MAIN)
        executable = temp / "oracle"
        subprocess.run([compiler, "-std=c99", "-O2", "-Wno-unknown-pragmas", "-I", str(temp),
                        str(oracle), "-o", str(executable)], check=True)
        completed = subprocess.run([str(executable)], text=True, capture_output=True, check=True)
    rows = [list(map(int, line.split()[1:])) for line in completed.stdout.splitlines() if line.startswith("GOLDEN ")]
    if len(rows) != count or any(len(row) != 11 for row in rows):
        raise ValueError("unexpected output from independent upstream oracle")
    lines = [
        "/* Generated by tests/generate_golden.py using reference/main.c. */",
        "/* Host mathematical oracle; not DSP execution or timing. */",
        "#ifndef CNN_GOLDEN_H", "#define CNN_GOLDEN_H",
        f"#define CNN_GOLDEN_COUNT {count}", f"#define CNN_GOLDEN_OFFSET {offset}",
        f'#define CNN_GOLDEN_DATA_SHA256 "{digest}"',
        f"static const long long cnn_golden_scores[{count}][10] = {{",
    ]
    lines.extend("    {" + ",".join(f"{value}LL" for value in row[1:]) + "}," for row in rows)
    lines.extend(["};", f"static const unsigned char cnn_golden_predictions[{count}] = {{",
                  "    " + ",".join(str(row[0]) for row in rows), "};", "#endif", ""])
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines))
    print(f"Generated {destination}: {count} independent upstream score vectors, offset={offset}, data SHA256={digest}.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        raise SystemExit(1)
